#!/usr/bin/env node
/**
 * Merge local env files into a single `vercel.env` for Vercel → Settings → Environment Variables → Import.
 * Reads secrets from artifacts/api-server/.env and public VITE_* from artifacts/samphone/.env(.local).
 * Output is gitignored — never commit vercel.env.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");

const SOURCES = [
  path.join(repoRoot, "artifacts", "api-server", ".env"),
  path.join(repoRoot, "artifacts", "samphone", ".env.local"),
  path.join(repoRoot, "artifacts", "samphone", ".env"),
];

/** Keys used on Vercel (serverless + Vite build). */
const VERCEL_KEYS = [
  "WOOCOMMERCE_STORE_URL",
  "WOOCOMMERCE_CONSUMER_KEY",
  "WOOCOMMERCE_CONSUMER_SECRET",
  "PRICING_ADMIN_TOKEN",
  "PRICING_ADMIN_EMAIL",
  "VITE_WOOCOMMERCE_STORE_URL",
  "VITE_WOOCOMMERCE_CURRENCY_SYMBOL",
  "VITE_WOO_API_BASE",
  "VITE_PRICING_API_URL",
  "VITE_WOO_EXTRA_PHONE_CATEGORY_SLUGS",
  "VITE_WOO_EXTRA_TABLET_CATEGORY_SLUGS",
];

const DEFAULTS = {
  VITE_WOOCOMMERCE_STORE_URL: "https://www.samphone.pt",
  VITE_WOOCOMMERCE_CURRENCY_SYMBOL: "€",
  VITE_WOO_API_BASE: "/api/woocommerce",
  VITE_PRICING_API_URL: "/api",
  PRICING_ADMIN_EMAIL: "admin@samphone.pt",
};

function parseEnvFile(filePath) {
  const out = {};
  if (!fs.existsSync(filePath)) return out;
  const text = fs.readFileSync(filePath, "utf8");
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

const merged = { ...DEFAULTS };
for (const src of SOURCES) {
  Object.assign(merged, parseEnvFile(src));
}

// Mirror store URL into VITE_ if only server key is set
if (!merged.VITE_WOOCOMMERCE_STORE_URL && merged.WOOCOMMERCE_STORE_URL) {
  merged.VITE_WOOCOMMERCE_STORE_URL = merged.WOOCOMMERCE_STORE_URL;
}
if (!merged.WOOCOMMERCE_STORE_URL && merged.VITE_WOOCOMMERCE_STORE_URL) {
  merged.WOOCOMMERCE_STORE_URL = merged.VITE_WOOCOMMERCE_STORE_URL;
}

const lines = [
  "# Import this file in Vercel: Project → Settings → Environment Variables → Import .env",
  "# Apply to: Production, Preview, and Development",
  "# Generated by: node scripts/merge-vercel-env.mjs",
  "# DO NOT commit this file (listed in .gitignore).",
  "",
  "# --- WooCommerce (server-side — powers /api/woocommerce on Vercel) ---",
];

for (const key of VERCEL_KEYS) {
  const value = merged[key];
  if (value === undefined || value === "") continue;
  if (key.startsWith("VITE_") && lines.some((l) => l.includes("# --- Storefront"))) {
    // already added section
  }
  if (key === "VITE_WOOCOMMERCE_STORE_URL") {
    lines.push("", "# --- Storefront (VITE_* — baked into build) ---");
  }
  lines.push(`${key}=${value}`);
}

const missing = ["WOOCOMMERCE_STORE_URL", "WOOCOMMERCE_CONSUMER_KEY", "WOOCOMMERCE_CONSUMER_SECRET"].filter(
  (k) => !merged[k],
);

const outPath = path.join(repoRoot, "vercel.env");
fs.writeFileSync(outPath, `${lines.join("\n")}\n`, "utf8");

console.log(`merge-vercel-env: wrote ${outPath}`);
if (missing.length) {
  console.warn(`merge-vercel-env: missing required keys: ${missing.join(", ")}`);
  console.warn("  Fill them in artifacts/api-server/.env and re-run this script.");
  process.exit(1);
}
